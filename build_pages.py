#!/usr/bin/env python3
"""Build the review previews pages/<name>.html from the Kajabi snippets kajabi/<name>.html.

The snippet is copied unchanged into a full HTML document. The preview adds only:
- a filler that renders each form placeholder's <template> (the field spec) as a working mock form,
  inserted just before the snippet's own <script> so the snippet treats it like the native form;
- the review state bar (pages/review-bar.js) with Norwegian state labels.
Run: python3 build_pages.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PAGES = {
    'registrering': ('Påmelding · gratis video',
        'before1:Før åpning (til 25. nov)|open1:Åpen (25. og 26. nov)|before2:Før runde 2 (27. nov til 8. des)'
        '|open2:Åpen (9. og 10. des)|closed:Stengt (fra 11. des)'),
    'takk': ('Takk for påmeldingen',
        'round1:Runde 1 (påmeldt før 25. nov)|round2:Runde 2 (påmeldt 27. nov til 8. des)'),
    'video': ('Video og tilbud',
        'before1:Før åpning (runde 1)|r1d1:Runde 1 · dag 1 (25. nov)|r1d2:Runde 1 · dag 2 (26. nov, direktesending 19.00)'
        '|r1d2vent:26. nov 19.45 til 21.00 (opptaket kommer)|between:Mellom rundene'
        '|before2:Før åpning (runde 2, ?runde=2)|r2d1:Runde 2 · dag 1 (9. des)'
        '|r2d2:Runde 2 · dag 2 (10. des, direktesending 12.00)|r2d2opptak:10. des fra 14.00 (opptak)|closed:Stengt (fra 11. des)'),
    'kalender': ('Romjulskalenderen',
        'locked:Skjema ikke fylt ut|feil:Feil e-post|waiting:Før 25. des|open:27. des (2 luker gjort)'
        '|alldone:Alle 8 luker gjort|closed:Stengt (fra 7. jan 2027)'),
}

MOCK_FORMS = """<script>/* preview only: render each empty form placeholder's field spec and route submits to the next preview */
document.querySelectorAll('.bw [data-kajabi-form]').forEach(function(ph){
  var t=ph.querySelector('template[data-preview-form]');if(!t||ph.querySelector('form'))return;
  ph.appendChild(t.content.cloneNode(true));
  var next=JSON.parse(t.getAttribute('data-next')||'{}');
  ph.querySelector('form').addEventListener('submit',function(e){e.preventDefault();var s=ph.closest('.bw').getAttribute('data-state');if(next[s])location.href=next[s];});
});
</script>
"""

TEMPLATE = """<!doctype html>
<html lang="no">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>{title} · til godkjenning</title>
<style>
body{{margin:0}}
:root{{--gold-d:#8a7340}}
{bar_css}
</style>
</head>
<body data-states="{states}">
<!-- ===== Kajabi snippet: kajabi/{name}.html (generated by build_pages.py, do not edit here) ===== -->
{snippet}
<!-- ===== end of snippet ===== -->
<script>document.documentElement.setAttribute('data-state',document.querySelector('.bw').getAttribute('data-state'));</script>
<script src="review-bar.js"></script>
</body>
</html>
"""


def main():
    shared = (ROOT / 'pages' / '_shared.css').read_text(encoding='utf-8')
    bar_css = '\n'.join(l for l in shared.splitlines() if l.startswith('.rv-bar'))
    for name, (title, states) in PAGES.items():
        snippet = (ROOT / 'kajabi' / f'{name}.html').read_text(encoding='utf-8').strip()
        i = snippet.rfind('<script>')
        assert i > 0, f'{name}: no inline <script> in snippet'
        body = snippet[:i] + MOCK_FORMS + snippet[i:]
        html = TEMPLATE.format(title=title, bar_css=bar_css, states=states, name=name, snippet=body)
        (ROOT / 'pages' / f'{name}.html').write_text(html, encoding='utf-8')
        print('pages/%s.html' % name)


if __name__ == '__main__':
    main()
